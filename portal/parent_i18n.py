def normalize_lang(code):
    code = (code or "").strip().lower()
    if code.startswith("es"):
        return "es"
    return "en"


def get_parent_language(request):
    if request is None:
        return "en"
    cached = getattr(request, "parent_lang", None)
    if cached in SUPPORTED_LANGUAGES:
        return cached
    session_lang = ""
    try:
        session_lang = request.session.get(SESSION_KEY) or ""
    except Exception:
        session_lang = ""
    cookie_lang = ""
    try:
        cookie_lang = request.COOKIES.get(COOKIE_NAME) or ""
    except Exception:
        cookie_lang = ""
    return normalize_lang(session_lang or cookie_lang or "en")


def set_parent_language(request, code):
    lang = normalize_lang(code)
    try:
        request.session[SESSION_KEY] = lang
        request.session.modified = True
    except Exception:
        pass
    request.parent_lang = lang
    return lang


def language_cookie_kwargs(lang):
    return {
        "key": COOKIE_NAME,
        "value": normalize_lang(lang),
        "max_age": 31536000,
        "path": "/",
        "samesite": "Lax",
    }


def is_parent_portal_request(request):
    path = (getattr(request, "path", "") or "").lower()
    if path.startswith("/portal/parent"):
        return True
    if "/portal/admin/parent-preview" in path:
        return True
    if path.startswith("/portal/login"):
        return False
    return False


def translate(lang, key, **kwargs):
    lang = normalize_lang(lang)
    text = _STRINGS.get(lang, {}).get(key) or _STRINGS["en"].get(key, key)
    if kwargs:
        try:
            text = text.format(**kwargs)
        except (KeyError, IndexError, ValueError):
            pass
    return text


def parent_language_context(request):
    return {"parent_lang": getattr(request, "parent_lang", "en")}


def translations(lang):
    lang = normalize_lang(lang)
    catalog = dict(_STRINGS["en"])
    catalog.update(_STRINGS.get(lang, {}))
    return catalog


def header_balance(preview):
    preview = preview or {}
    billing = preview.get("billing") or {}
    dashboard = preview.get("dashboard") or {}
    has_credit = bool(billing.get("has_credit") or dashboard.get("has_credit"))
    credit = dashboard.get("account_credit") or billing.get("account_credit") or "0.00"
    amount = dashboard.get("balance") or billing.get("running_balance") or "0.00"
    balance_due = billing.get("balance_due") or amount
    is_zero = str(amount) in ("0", "0.00", "0.0") and not has_credit
    return {
        "has_credit": has_credit,
        "credit": credit,
        "amount": amount,
        "balance_due": balance_due,
        "is_zero": is_zero,
        "pay_ahead": has_credit or str(balance_due) in ("0", "0.00", "0.0"),
    }


def last_paid_receipt(receipts):
    for receipt in receipts or []:
        reference = str(receipt.get("reference") or "")
        if "RCPT" in reference:
            return receipt
    return None


