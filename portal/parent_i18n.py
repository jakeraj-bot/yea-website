def translate_label(lang, value):
    if value is None:
        return ""
    text = str(value).strip()
    if not text:
        return text
    lang = normalize_lang(lang)
    key = _VALUE_KEYS.get(text.lower())
    if key:
        return translate(lang, key)
    if lang != "es":
        return text
    lower = text.lower()
    for prefix, prefix_key in _PREFIX_KEYS:
        if lower.startswith(prefix):
            return translate(lang, prefix_key) + text[len(prefix) :]
    out = text
    for english, spanish in _MONTHS_EN_ES:
        out = out.replace(english, spanish)
    return out


