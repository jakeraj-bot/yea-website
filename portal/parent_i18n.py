def is_parent_portal_request(request):
    path = (getattr(request, "path", "") or "").lower()
    if path.startswith("/portal/parent"):
        return True
    if "/portal/admin/parent-preview" in path:
        return True
    if path.startswith("/portal/login"):
        return False
    return False


