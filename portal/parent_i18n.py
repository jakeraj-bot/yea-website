    lang = normalize_lang(lang)
    text = _STRINGS.get(lang, {}).get(key) or _STRINGS["en"].get(key, key)
    if kwargs:
        try:
            text = text.format(**kwargs)
        except (KeyError, IndexError, ValueError):
            pass
    return text


