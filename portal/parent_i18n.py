def header_balance(preview):
    preview = preview or {}
    billing = preview.get("billing") or {}
    dashboard = preview.get("dashboard") or {}
    has_credit = bool(billing.get("has_credit") or dashboard.get("has_credit"))
    credit = dashboard.get("account_credit") or billing.get("account_credit") or "0.00"
    amount = dashboard.get("balance") or billing.get("running_balance") or "0.00"
    balance_due = billing.get("balance_due") or amount
    is_zero = str(amount) in ("0", "0.00", "0.0") and not has_credit
    return {
        "has_credit": has_credit,
        "credit": credit,
        "amount": amount,
        "balance_due": balance_due,
        "is_zero": is_zero,
        "pay_ahead": has_credit or str(balance_due) in ("0", "0.00", "0.0"),
    }


def last_paid_receipt(receipts):
    for receipt in receipts or []:
        reference = str(receipt.get("reference") or "")
        if "RCPT" in reference:
            return receipt
    return None


